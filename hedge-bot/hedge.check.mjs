import {test} from 'node:test';
import assert from 'node:assert/strict';
import {decide} from './hedge.mjs';
const cfg={"target":1,"maxDrawdown":0.15,"maxPositions":5,"maxSpread":0.5,"gridDistance":2,"cooldownMs":30000,"volume":0.01};
const state={"equity":100,"peakEquity":100,"positions":[{"id":"old","side":"BUY","entry":4000,"netPnl":-3}],"lastEntryTime":0,"paused":false};
const q={"bid":3997,"ask":3997.2,"ageMs":10,"signal":"SELL","time":40000};
test('keep loser and add opposite paper entry',()=>{const r=decide(state,q,cfg);assert.equal(r.open.side,'SELL');assert.deepEqual(r.close,[])});
test('close winners only',()=>assert.deepEqual(decide({...state,positions:[...state.positions,{id:'win',side:'SELL',entry:4002,netPnl:1}]},q,cfg).close,['win']));
test('stale blocked',()=>assert.equal(decide(state,{...q,ageMs:10001},cfg).status,'STALE'));
test('drawdown emergency',()=>assert.equal(decide({...state,equity:80},q,cfg).status,'EMERGENCY'));
test('position cap',()=>assert.equal(decide({...state,positions:Array.from({length:5},(_,i)=>({...state.positions[0],id:String(i)}))},q,cfg).open,null));
test('grid distance',()=>assert.equal(decide(state,{...q,bid:3999,ask:3999.2,signal:'BUY'},cfg).status,'GRID_WAIT'));
