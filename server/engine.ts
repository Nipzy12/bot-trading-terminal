import { createHmac, randomBytes } from "node:crypto";
import express from "express";
import { z } from "zod";
import { database, takeRate } from "./database.js";
import type { Identity } from "./accounts.js";

// The Windows process is a heartbeat-only device. It never receives Exness secrets,
// broker permissions, market quotes, or commands through these routes.
const pairCode = z.string().regex(/^[A-Za-z0-9_-]{32}$/);
const bearer = /^Bearer ([A-Za-z0-9_-]{43})$/;
const deviceLabel = "Windows laptop";
const presenceWindowMs = 30_000;
export const livePermissionMinutes = 30;
// No broker authorization header is generated by V6.2B Phase 1.
// This is an explicit owner consent gate for a future, narrowly signed GET handshake.
export const liveConsentSchema = z.object({
  readOnlyKeyConfirmed: z.literal(true),
  temporaryApiIdentifierAcknowledged: z.literal(true),
}).strict();
export function engineLivePermission(expiry: unknown, now = Date.now()) {
  if (!expiry) return false;
  const at = new Date(expiry as string).getTime();
  return Number.isFinite(at) && at > now && at - now <= livePermissionMinutes * 60_000;
}


// V6.2A only: isolated, explicitly synthetic transport fixture.
// Never feeds order execution, broker balances, the chart or EXNESS_LIVE status.
export const relayTestSchema = z.object({
  mode: z.literal("TEST_ONLY"),
  symbol: z.literal("XAUUSD"),
  bid: z.number().finite().positive().max(1000000),
  ask: z.number().finite().positive().max(1000000),
  at: z.iso.datetime({ offset: true }),
}).strict();
export function validateRelayTest(value: unknown, now = Date.now()) {
  const result = relayTestSchema.safeParse(value);
  if (!result.success) return null;
  const quote = result.data;
  const t = Date.parse(quote.at);
  if (!Number.isFinite(t) || t < now - 10_000 || t > now + 2_000 ||
      quote.ask < quote.bid || quote.ask - quote.bid > 100) return null;
  return quote;
}
export function relayTestFresh(receivedAt: unknown, heartbeatAt: unknown, now = Date.now()) {
  if (enginePresence(heartbeatAt, now) !== "ONLINE" || !receivedAt) return false;
  const t = new Date(receivedAt as string).getTime();
  return Number.isFinite(t) && t <= now && now - t <= 15_000;
}

export function engineSecretHash(kind: string, value: string, key = process.env.BETTER_AUTH_SECRET ?? "") {
  if (key.length < 32) throw Error("ENGINE_AUTH_UNAVAILABLE");
  return createHmac("sha256", key).update("nexus-engine-v1:").update(kind).update(":").update(value).digest("hex");
}
export function enginePresence(lastSeen: unknown, now = Date.now()): "ONLINE" | "OFFLINE" {
  if (!lastSeen) return "OFFLINE";
  const timestamp = new Date(lastSeen as string).getTime();
  return Number.isFinite(timestamp) && timestamp <= now && now - timestamp <= presenceWindowMs
    ? "ONLINE" : "OFFLINE";
}
function newCode() { return randomBytes(24).toString("base64url"); }
function newToken() { return randomBytes(32).toString("base64url"); }

export function ownerEngineRouter() {
  const router = express.Router();
  router.get("/status", async (_req, res) => {
    try {
      const owner = (res.locals.identity as Identity).user.id;
      const result = await database().query(
        "SELECT label,paired_at,last_seen_at FROM nexus_private.nexus_engine_devices WHERE user_id=$1",
        [owner],
      );
      const row = result.rows[0];
      res.json(row
        ? { status: enginePresence(row.last_seen_at), label: row.label,
            pairedAt: row.paired_at, lastSeenAt: row.last_seen_at }
        : { status: "UNPAIRED", label: null, pairedAt: null, lastSeenAt: null });
    } catch {
      res.status(503).json({ error: "ENGINE_SERVICE_UNAVAILABLE" });
    }
  });
  router.get("/relay-test", async (_req, res) => {
    try {
      const owner = (res.locals.identity as Identity).user.id;
      const result = await database().query(
        "SELECT q.symbol,q.bid,q.ask,q.quote_at,q.received_at,d.last_seen_at FROM nexus_private.nexus_engine_test_quotes q JOIN nexus_private.nexus_engine_devices d ON d.user_id=q.user_id WHERE q.user_id=$1",
        [owner],
      );
      const row = result.rows[0];
      if (!row || !relayTestFresh(row.received_at, row.last_seen_at)) {
        res.json({ source: "TEST_ONLY", fresh: false, symbol: null, bid: null, ask: null });
        return;
      }
      res.json({ source: "TEST_ONLY", fresh: true, symbol: row.symbol,
        bid: Number(row.bid), ask: Number(row.ask), sampledAt: row.quote_at });
    } catch {
      res.status(503).json({ error: "ENGINE_SERVICE_UNAVAILABLE" });
    }
  });
  router.get("/live-permission", async (_req, res) => {
    try {
      const owner = (res.locals.identity as Identity).user.id;
      const rows = await database().query(
        "SELECT expires_at FROM nexus_private.nexus_engine_live_permission WHERE user_id=$1",
        [owner],
      );
      const expires = rows.rows[0]?.expires_at;
      res.json({
        permission: engineLivePermission(expires) ? "TEMPORARY_ALLOWED" : "DISABLED",
        expiresAt: engineLivePermission(expires) ? expires : null,
        brokerOrders: false,
        phase: "CONSENT_ONLY",
      });
    } catch {
      res.status(503).json({ error: "ENGINE_SERVICE_UNAVAILABLE" });
    }
  });
  router.post("/live-permission", async (req, res) => {
    if (!liveConsentSchema.safeParse(req.body).success) {
      res.status(400).json({ error: "EXPLICIT_CONSENT_REQUIRED" }); return;
    }
    try {
      const owner = (res.locals.identity as Identity).user.id;
      const db = database();
      const eligible = await db.query(
        "SELECT d.user_id FROM nexus_private.nexus_engine_devices d JOIN nexus_private.nexus_selection s ON s.user_id=d.user_id JOIN nexus_private.nexus_credentials c ON c.id=s.credential_id AND c.user_id=d.user_id WHERE d.user_id=$1 AND c.status='verified'",
        [owner],
      );
      if (!eligible.rows.length) {
        res.status(409).json({ error: "PAIRED_DEVICE_AND_VERIFIED_EXNESS_REQUIRED" }); return;
      }
      if (!(await takeRate(db, "engine-live-consent:" + owner, 4, 3600))) {
        res.status(429).json({ error: "RATE_LIMITED" }); return;
      }
      const permit = await db.query(
        "INSERT INTO nexus_private.nexus_engine_live_permission(user_id,expires_at) VALUES($1,clock_timestamp()+interval '30 minutes') ON CONFLICT (user_id) DO UPDATE SET expires_at=EXCLUDED.expires_at RETURNING expires_at",
        [owner],
      );
      res.json({
        permission: "TEMPORARY_ALLOWED",
        expiresAt: permit.rows[0].expires_at,
        phase: "CONSENT_ONLY",
        brokerOrders: false,
      });
    } catch {
      res.status(503).json({ error: "ENGINE_SERVICE_UNAVAILABLE" });
    }
  });
  router.delete("/live-permission", async (_req, res) => {
    try {
      const owner = (res.locals.identity as Identity).user.id;
      await database().query(
        "DELETE FROM nexus_private.nexus_engine_live_permission WHERE user_id=$1",
        [owner],
      );
      res.json({ revoked: true, permission: "DISABLED", brokerOrders: false });
    } catch {
      res.status(503).json({ error: "ENGINE_SERVICE_UNAVAILABLE" });
    }
  });
  // Inherits authenticated session, exact-Origin/CSRF and owner rate limiting from /api/account.
  router.post("/pair-code", async (_req, res) => {
    try {
      const owner = (res.locals.identity as Identity).user.id;
      if (!(await takeRate(database(), "engine-pair-create:" + owner, 5, 3600))) {
        res.status(429).json({ error: "RATE_LIMITED" }); return;
      }
      const code = newCode();
      const hash = engineSecretHash("pair", code);
      await database().query(
        "INSERT INTO nexus_private.nexus_engine_pairing(user_id,code_hash,expires_at) VALUES($1,$2,clock_timestamp()+interval '5 minutes') ON CONFLICT(user_id) DO UPDATE SET code_hash=EXCLUDED.code_hash,expires_at=EXCLUDED.expires_at",
        [owner, hash],
      );
      res.set("Cache-Control", "no-store").json({ code, expiresInSeconds: 300 });
    } catch {
      res.status(503).json({ error: "ENGINE_SERVICE_UNAVAILABLE" });
    }
  });
  router.post("/revoke", async (_req, res) => {
    try {
      const owner = (res.locals.identity as Identity).user.id;
      await database().query("DELETE FROM nexus_private.nexus_engine_pairing WHERE user_id=$1", [owner]);
      await database().query("DELETE FROM nexus_private.nexus_engine_devices WHERE user_id=$1", [owner]);
      await database().query("DELETE FROM nexus_private.nexus_engine_live_permission WHERE user_id=$1", [owner]);
      res.json({ revoked: true });
    } catch {
      res.status(503).json({ error: "ENGINE_SERVICE_UNAVAILABLE" });
    }
  });
  return router;
}

export function deviceEngineRouter() {
  const router = express.Router();
  router.post("/pair", async (req, res) => {
    const parsed = z.object({ code: pairCode }).strict().safeParse(req.body);
    if (!parsed.success) { res.status(400).json({ error: "INVALID_PAIR_CODE" }); return; }
    try {
      // This unauthenticated claim endpoint uses high-entropy, single-use codes and
      // shared PostgreSQL rate limiting. No client-provided owner identity is trusted.
      const address = (process.env.VERCEL === "1"
        ? req.get("x-vercel-forwarded-for") : undefined) ?? req.socket.remoteAddress ?? "unknown";
      const bucket = engineSecretHash("ip", address);
      if (!(await takeRate(database(), "engine-claim:" + bucket, 12, 60))) {
        res.status(429).json({ error: "RATE_LIMITED" }); return;
      }
      const token = newToken();
      const tokenHash = engineSecretHash("device", token);
      const codeHash = engineSecretHash("pair", parsed.data.code);
      const result = await database().query(
        "WITH claimed AS (DELETE FROM nexus_private.nexus_engine_pairing WHERE code_hash=$1 AND expires_at>clock_timestamp() RETURNING user_id) INSERT INTO nexus_private.nexus_engine_devices(user_id,token_hash,label,paired_at,last_seen_at) SELECT user_id,$2,$3,clock_timestamp(),NULL FROM claimed ON CONFLICT(user_id) DO UPDATE SET token_hash=EXCLUDED.token_hash,label=EXCLUDED.label,paired_at=clock_timestamp(),last_seen_at=NULL RETURNING user_id",
        [codeHash, tokenHash, deviceLabel],
      );
      if (result.rows.length !== 1) { res.status(403).json({ error: "PAIR_CODE_EXPIRED_OR_USED" }); return; }
      // Device token is returned once and kept only in process memory by the Windows CLI.
      res.set("Cache-Control", "no-store").json({ paired: true, token, heartbeatSeconds: 10 });
    } catch {
      res.status(503).json({ error: "ENGINE_SERVICE_UNAVAILABLE" });
    }
  });
  router.post("/relay-test", async (req, res) => {
    const token = bearer.exec(req.get("authorization") ?? "");
    if (!token) { res.status(401).json({ error: "ENGINE_UNAUTHORIZED" }); return; }
    const quote = validateRelayTest(req.body);
    if (!quote) { res.status(400).json({ error: "INVALID_TEST_QUOTE" }); return; }
    try {
      const db = database();
      const hash = engineSecretHash("device", token[1]);
      const device = await db.query(
        "SELECT user_id FROM nexus_private.nexus_engine_devices WHERE token_hash=$1 AND last_seen_at > clock_timestamp()-interval '30 seconds'",
        [hash],
      );
      if (!device.rows.length) { res.status(401).json({ error: "ENGINE_UNAUTHORIZED" }); return; }
      const owner = device.rows[0].user_id as string;
      if (!(await takeRate(db, "engine-test-relay:" + owner, 8, 60))) {
        res.status(429).json({ error: "RATE_LIMITED" }); return;
      }
      const stored = await db.query(
        `INSERT INTO nexus_private.nexus_engine_test_quotes(user_id,symbol,bid,ask,quote_at,received_at)
         SELECT user_id,$2,$3,$4,$5,clock_timestamp() FROM nexus_private.nexus_engine_devices
         WHERE token_hash=$1 AND last_seen_at>clock_timestamp()-interval '30 seconds'
         ON CONFLICT(user_id) DO UPDATE SET symbol=EXCLUDED.symbol,bid=EXCLUDED.bid,ask=EXCLUDED.ask,
           quote_at=EXCLUDED.quote_at,received_at=EXCLUDED.received_at
         WHERE nexus_engine_test_quotes.quote_at<EXCLUDED.quote_at RETURNING user_id`,
        [hash, quote.symbol, quote.bid, quote.ask, quote.at],
      );
      if (!stored.rows.length) { res.status(409).json({ error: "RELAY_REJECTED" }); return; }
      res.json({ accepted: true, source: "TEST_ONLY", brokerVerified: false });
    } catch {
      res.status(503).json({ error: "ENGINE_SERVICE_UNAVAILABLE" });
    }
  });
  // Device can inspect owner authorization, but no Exness credential or signing material is returned.
  router.post("/live-permission", async (req, res) => {
    const found = bearer.exec(req.get("authorization") ?? "");
    if (!found) { res.status(401).json({ error: "ENGINE_UNAUTHORIZED" }); return; }
    try {
      const db = database();
      const hash = engineSecretHash("device", found[1]);
      const rows = await db.query(
        "SELECT p.expires_at FROM nexus_private.nexus_engine_devices d LEFT JOIN nexus_private.nexus_engine_live_permission p ON p.user_id=d.user_id WHERE d.token_hash=$1 AND d.last_seen_at>clock_timestamp()-interval '30 seconds'",
        [hash],
      );
      if (!rows.rows.length) { res.status(401).json({ error: "ENGINE_UNAUTHORIZED" }); return; }
      const expiry = rows.rows[0].expires_at;
      res.json({
        permission: engineLivePermission(expiry) ? "TEMPORARY_ALLOWED" : "DISABLED",
        expiresAt: engineLivePermission(expiry) ? expiry : null,
        phase: "CONSENT_ONLY",
        brokerOrders: false,
      });
    } catch {
      res.status(503).json({ error: "ENGINE_SERVICE_UNAVAILABLE" });
    }
  });
  router.post("/heartbeat", async (req, res) => {
    const found = bearer.exec(req.get("authorization") ?? "");
    if (!found) { res.status(401).json({ error: "ENGINE_UNAUTHORIZED" }); return; }
    try {
      const hash = engineSecretHash("device", found[1]);
      if (!(await takeRate(database(), "engine-beat:" + hash, 12, 60))) {
        res.status(429).json({ error: "RATE_LIMITED" }); return;
      }
      const result = await database().query(
        "UPDATE nexus_private.nexus_engine_devices SET last_seen_at=clock_timestamp() WHERE token_hash=$1 RETURNING user_id",
        [hash],
      );
      if (result.rows.length !== 1) { res.status(401).json({ error: "ENGINE_UNAUTHORIZED" }); return; }
      res.json({ acknowledged: true, brokerOrders: false, mode: "HEARTBEAT_ONLY" });
    } catch {
      res.status(503).json({ error: "ENGINE_SERVICE_UNAVAILABLE" });
    }
  });
  return router;
}
